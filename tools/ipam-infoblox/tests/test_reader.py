import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ipam_infoblox.reader import map_columns, read_table  # noqa: E402

FIXTURE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "ipam-export.csv")

try:
    import openpyxl
except ImportError:  # pragma: no cover - optional dependency
    openpyxl = None


def write(text, suffix=".csv"):
    handle = tempfile.NamedTemporaryFile("w", suffix=suffix, delete=False, encoding="utf-8")
    handle.write(text)
    handle.close()
    return handle.name


class CsvTest(unittest.TestCase):
    def test_header_found_below_a_title(self):
        table = read_table(FIXTURE)
        self.assertEqual(table.header_row, 3)
        self.assertEqual(len(table.rows), 12)
        self.assertEqual(table.rows[0][0], 4)  # data rows keep their spreadsheet row numbers
        columns = map_columns(table)
        self.assertEqual(columns["cidr"], "Resource CIDR")
        self.assertEqual(columns["account"], "Resource owner")
        self.assertEqual(columns["name"], "Resource name")
        self.assertNotIn("description", columns)

    def test_other_spellings_and_delimiters(self):
        path = write("VpcId;CidrBlock;OwnerId;Tag Name\nvpc-1;10.9.0.0/16;111122223333;lab\n")
        self.addCleanup(os.remove, path)
        table = read_table(path)
        columns = map_columns(table)
        self.assertEqual((columns["cidr"], columns["account"], columns["name"]),
                         ("CidrBlock", "OwnerId", "Tag Name"))
        self.assertEqual(table.rows[0][1]["CidrBlock"], "10.9.0.0/16")

    def test_overrides(self):
        path = write("Block,Who\n10.9.0.0/16,lab\n")
        self.addCleanup(os.remove, path)
        with self.assertRaisesRegex(ValueError, "no header row with a CIDR column"):
            read_table(path)
        path = write("CIDR,Block,Who\n,10.9.0.0/16,lab\n")
        self.addCleanup(os.remove, path)
        table = read_table(path)
        columns = map_columns(table, {"cidr": "block", "name": "Who"})
        self.assertEqual((columns["cidr"], columns["name"]), ("Block", "Who"))
        with self.assertRaisesRegex(ValueError, "no such column"):
            map_columns(table, {"cidr": "Nope"})
        with self.assertRaisesRegex(ValueError, "unknown field"):
            map_columns(table, {"colour": "Who"})

    def test_repeated_and_blank_headers_are_kept_apart(self):
        path = write("CIDR,,Name,Name\n10.9.0.0/16,x,a,b\n")
        self.addCleanup(os.remove, path)
        table = read_table(path)
        self.assertEqual(table.headers, ["CIDR", "column 2", "Name", "Name (2)"])

    def test_old_excel_and_missing_files(self):
        path = write("", suffix=".xls")
        self.addCleanup(os.remove, path)
        with self.assertRaisesRegex(ValueError, "save it as .xlsx or CSV"):
            read_table(path)
        with self.assertRaisesRegex(FileNotFoundError, "no such file"):
            read_table("missing.xlsx")


@unittest.skipIf(openpyxl is None, "needs openpyxl")
class ExcelTest(unittest.TestCase):
    def workbook(self):
        book = openpyxl.Workbook()
        book.active.title = "Summary"
        book.active.append(["Generated by AWS IPAM"])
        sheet = book.create_sheet("Resources")
        sheet.append(["IPAM resources"])
        sheet.append([])
        sheet.append(["Resource ID", "Resource CIDR", "Resource owner"])
        sheet.append(["vpc-0a1b2c3d4e5f60001", "10.0.0.0/16", 111122223333])
        handle = tempfile.NamedTemporaryFile(suffix=".xlsx", delete=False)
        handle.close()
        book.save(handle.name)
        self.addCleanup(os.remove, handle.name)
        return handle.name

    def test_finds_the_sheet_and_header(self):
        table = read_table(self.workbook())
        map_columns(table)
        self.assertEqual((table.sheet, table.header_row), ("Resources", 3))
        number, values = table.rows[0]
        self.assertEqual(number, 4)
        self.assertEqual(values["Resource owner"], "111122223333")  # not 111122223333.0

    def test_named_sheet(self):
        path = self.workbook()
        with self.assertRaisesRegex(ValueError, "no sheet named"):
            read_table(path, "Nope")
        with self.assertRaisesRegex(ValueError, "no sheet has a header"):
            read_table(path, "Summary")


if __name__ == "__main__":
    unittest.main()
